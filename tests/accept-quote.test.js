import test from "node:test";
import assert from "node:assert/strict";
import "fake-indexeddb/auto";
import { InvoiceRepository } from "../src/storage/repository.js";
import { calculate, today } from "../src/domain/invoice.js";

test("accepting a quote atomically creates one independent issued invoice with copied files", async () => {
  const r = new InvoiceRepository(`accept-${crypto.randomUUID()}`);
  let q = await r.create("Quote");
  q.customerName = "Accepted customer";
  q.projectTitle = "Kitchen";
  q.validUntil = "2099-01-01";
  q.quoteTerms = "Approval required";
  q.terms = "Net 30";
  const fileId = crypto.randomUUID();
  q.attachments = [{ id: fileId, name: "Receipt.pdf", type: "application/pdf", category: "Receipt / material list", invoiceAmount: 107, taxIncluded: true, showOnInvoice: true }];
  q = await r.save(q, { action: "issue", uploads: [{ id: fileId, blob: new Blob(["receipt"]) }] });
  const [invoice, retry] = await Promise.all([r.acceptQuote(q), r.acceptQuote(q)]);
  assert.equal(invoice.id, retry.id);
  assert.equal((await r.list()).length, 2);
  assert.equal(invoice.type, "Invoice");
  assert.equal(invoice.status, "Issued");
  assert.notEqual(invoice.number, q.number);
  assert.equal(invoice.sourceQuoteId, q.id);
  assert.equal(invoice.date, today());
  assert.equal(invoice.dueDate, "");
  assert.equal(invoice.validUntil, undefined);
  assert.equal(invoice.quoteTerms, undefined);
  assert.equal(invoice.terms, "Net 30");
  assert.equal(invoice.projectTitle, "Kitchen");
  assert.deepEqual(calculate(invoice), calculate(q));
  assert.notEqual(invoice.attachments[0].id, fileId);
  const file = await r.attachment(invoice.attachments[0].id);
  assert.equal(file.documentId, invoice.id);
  assert.equal(await file.blob.text(), "receipt");
  assert.equal((await r.attachment(fileId)).documentId, q.id);
  const accepted = await r.get(q.id);
  assert.ok(accepted.acceptedAt);
  assert.equal(accepted.invoiceId, invoice.id);
  assert.equal(accepted.history.at(-1).action, `Accepted; created invoice ${invoice.number}`);
  await r.save({ ...accepted, invoiceId: null, notes: "Later correction" });
  assert.equal((await r.get(q.id)).invoiceId, invoice.id);
  assert.equal((await r.get(invoice.id)).notes, q.notes);
  await r.save(invoice, { action: "paid", detail: { paidDate: today() } });
  assert.equal((await r.acceptQuote(q)).status, "Paid");
});

test("invalid, stale and missing-file quotes do not leave partial invoices", async () => {
  const r = new InvoiceRepository(`accept-errors-${crypto.randomUUID()}`);
  let q = await r.create("Quote");
  await assert.rejects(r.acceptQuote(q), /Issue the quote/);
  q.customerName = "Customer";
  const stale = q;
  q = await r.save(q, { action: "issue" });
  await assert.rejects(r.acceptQuote(stale), /changed/);
  q.attachments = [{ id: crypto.randomUUID(), name: "Lost file", missing: true }];
  q = await r.save(q);
  await assert.rejects(r.acceptQuote(q), /missing attachment/);
  assert.equal((await r.list()).length, 1);
  assert.equal((await r.get(q.id)).acceptedAt, undefined);
  q = await r.save(q, { action: "void", detail: { reason: "Cancelled" } });
  await assert.rejects(r.acceptQuote(q), /Issue the quote/);
  assert.equal((await r.create()).number, "HA-0002");
});
